"""Build (and optionally push) a private Kaggle script notebook that runs the step-1 audit on T4 x2.

Kaggle script notebooks are one .py file with internet off, so this script packs grokpred/ and audit.py
into the notebook as compressed text, records their sha256, and adds a small scheduler that keeps both
GPUs busy. Results land in /kaggle/working/runs/audit/ and come back with `kaggle kernels output`.

  KAGGLE_USERNAME=<you> python kaggle_launch.py           # writes kaggle/<slug>/kernel.py + kernel-metadata.json
  KAGGLE_USERNAME=<you> python kaggle_launch.py --push    # also uploads and starts it
The Kaggle CLI is taken from $KAGGLE_CLI if set, else `kaggle` on the PATH.
"""
import argparse
import base64
import hashlib
import json
import os
import pathlib
import subprocess
import zlib

ROOT = pathlib.Path(__file__).resolve().parent
KAGGLE = os.environ.get("KAGGLE_CLI", "kaggle")
FILES = ["grokpred/__init__.py", "grokpred/data.py", "grokpred/model.py", "grokpred/losses.py",
         "grokpred/optim.py", "grokpred/train.py", "audit.py"]

# (variant, extra args). Two queues, one per GPU, balanced by expected run time: the float32
# variants take ~20-40 min each on a T4; ref64 (12 replicas, float64) a few hours, since the T4's
# float64 throughput is 1/32 of float32.
QUEUES = [
    [("ce32", []), ("margin32", []), ("ce32_ulp", [])],
    [("ce64", []), ("ref64", [])],
]

TEMPLATE = '''"""Step-1 numerics audit (generated by grok-boundary/kaggle_launch.py; do not edit here)."""
import base64, json, os, subprocess, sys, time, zlib
SOURCES = json.loads(r"""{sources}""")
SHA256 = json.loads(r"""{sha}""")
QUEUES = json.loads(r"""{queues}""")
STEPS = {steps}
SRC = os.environ.get("GB_SRC", "/tmp/gb")
WORK = os.environ.get("GB_WORK", "/kaggle/working")
DEVICE = os.environ.get("GB_DEVICE", "cuda")
for rel, blob in SOURCES.items():
    path = os.path.join(SRC, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "wb").write(zlib.decompress(base64.b64decode(blob)))
os.makedirs(f"{{WORK}}/runs/audit", exist_ok=True)
json.dump(SHA256, open(f"{{WORK}}/runs/audit/source_sha256.json", "w"), indent=1)
import torch
print("torch", torch.__version__, [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())], flush=True)
if DEVICE == "cuda":
    assert torch.cuda.device_count() >= len(QUEUES), f"need {{len(QUEUES)}} GPUs, have {{torch.cuda.device_count()}}"

def run_queue(gpu, queue):
    procs = []
    for variant, extra in queue:
        cmd = [sys.executable, "audit.py", "--variant", variant, "--steps", str(STEPS),
               "--device", DEVICE, "--out", f"{{WORK}}/runs/audit"] + extra
        log = open(f"{{WORK}}/runs/audit/{{variant}}.log", "w")
        env = dict(os.environ, CUDA_VISIBLE_DEVICES=str(gpu), PYTHONPATH=SRC)
        procs.append((variant, cmd, log, env))
    return procs

# One process per GPU at a time; each GPU works through its own queue.
queues = [run_queue(g, q) for g, q in enumerate(QUEUES)]
active, failed = {{}}, []
t0 = time.time()
while any(queues) or active:
    for g in range(len(queues)):
        if g not in active and queues[g]:
            variant, cmd, log, env = queues[g].pop(0)
            active[g] = (variant, subprocess.Popen(cmd, cwd=SRC, stdout=log, stderr=subprocess.STDOUT, env=env), log)
            print(f"[{{time.time()-t0:7.0f}}s] gpu{{g}} start {{variant}}", flush=True)
    for g, (variant, proc, log) in list(active.items()):
        if proc.poll() is not None:
            log.close()
            print(f"[{{time.time()-t0:7.0f}}s] gpu{{g}} end {{variant}} rc={{proc.returncode}}", flush=True)
            if proc.returncode != 0:
                failed.append(variant)
            print(open(f"{{WORK}}/runs/audit/{{variant}}.log").read()[-1500:], flush=True)
            del active[g]
    time.sleep(10)
print("all done", time.time() - t0, "failed:", failed, flush=True)
if failed:
    sys.exit(1)
'''


def build(steps: int, slug: str):
    sources, sha = {}, {}
    for rel in FILES:
        data = (ROOT / rel).read_bytes()
        sources[rel] = base64.b64encode(zlib.compress(data, 9)).decode()
        sha[rel] = hashlib.sha256(data).hexdigest()
    out_dir = ROOT / "kaggle" / slug
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "kernel.py").write_text(TEMPLATE.format(
        sources=json.dumps(sources), sha=json.dumps(sha, indent=1), queues=json.dumps(QUEUES), steps=steps))
    user = os.environ.get("KAGGLE_USERNAME")
    if not user:
        raise SystemExit("set KAGGLE_USERNAME to the Kaggle account that will own the notebook")
    meta = {"id": f"{user}/{slug}", "title": slug.replace("-", " "), "code_file": "kernel.py",
            "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
            "enable_tpu": False, "enable_internet": False, "dataset_sources": [], "kernel_sources": [],
            "competition_sources": [], "model_sources": [], "machine_shape": "NvidiaTeslaT4"}
    (out_dir / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    (out_dir / "source_sha256.json").write_text(json.dumps(sha, indent=1))
    return out_dir


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--steps", type=int, default=100_000)
    ap.add_argument("--slug", default="grok-boundary-audit")
    ap.add_argument("--push", action="store_true")
    a = ap.parse_args()
    d = build(a.steps, a.slug)
    print("wrote", d)
    if a.push:
        subprocess.run([str(KAGGLE), "kernels", "push", "-p", str(d)], check=True)
